export function mapMidiCcToRange(
  ccValue: number,
  min: number,
  max: number,
  step: number
): number {
  const norm = Math.max(0, Math.min(1, ccValue / 127));
  const raw = min + norm * (max - min);
  const snapped = Math.round(raw / step) * step;
  const decimals = step < 0.01 ? 3 : step < 0.1 ? 2 : step < 1 ? 1 : 0;
  return Math.max(min, Math.min(max, Number(snapped.toFixed(decimals))));
}
